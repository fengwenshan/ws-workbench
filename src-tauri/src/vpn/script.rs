    #[cfg(target_os = "windows")]
    #[test]
    fn windows_script_compiles_under_cscript() {
        // 直接复现踩过的坑：脚本里只要混进一个非 ASCII 字节，cscript 就按系统
        // ANSI 代码页解码失败并退出 1，而 openconnect 只会把它曲解成
        // "Failed to spawn script"。所以这里真的把脚本交给 cscript 编译一遍。
        let dir = crate::test_support::TempDir::new("script-check");
        let path = dir.join("vpnc-script-win.js");

        std::fs::write(&path, windows_script(&ctx())).unwrap();
        // reason 显式置空：脚本两个分支都不进，只会 WScript.Quit(0)，
        // 不会执行任何 netsh / route，动不到本机的网络配置。
        let output = std::process::Command::new("cscript.exe")
            .args(["//nologo", "//E:JScript"])
            .arg(&path)
            .env("reason", "")
            .output()
            .expect("cscript.exe 是 Windows 自带组件，应当可用");
        assert!(
            output.status.success(),
            "cscript 无法执行生成的脚本（{:?}）: {}{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }

    #[cfg(target_os = "windows")]
    #[test]
    fn windows_script_reports_split_scope_through_cscript() {
        // 真正用 cscript 跑一遍 connect 分支的「回报」部分：地址 / 网关 / MTU 全空，
        // 所以脚本不会执行任何 netsh / route，只会把服务端下发的范围写进 script.log
        // 和 stdout，动不到本机网络。
        let dir = crate::test_support::TempDir::new("script-split");
        let path = dir.join("vpnc-script-win.js");
        let ctx = ScriptContext {
            session_dir: dir.path(),
            original_gateway: "192.168.1.1",
        };
        std::fs::write(&path, windows_script(&ctx)).unwrap();
        let output = std::process::Command::new("cscript.exe")
            .args(["//nologo", "//E:JScript"])
            .arg(&path)
            .env("reason", "connect")
            .env("TUNDEV", "ws-tun")
            .env("TUNIDX", "77")
            .env("INTERNAL_IP4_ADDRESS", "")
            .env("INTERNAL_IP4_MTU", "")
            .env("INTERNAL_IP4_DNS", "192.0.2.12")
            .env("VPNGATEWAY", "")
            .env("CISCO_DEF_DOMAIN", "example.com")
            .env("CISCO_SPLIT_INC", "2")
            .env("CISCO_SPLIT_INC_0_ADDR", "198.51.100.0")
            .env("CISCO_SPLIT_INC_0_MASKLEN", "22")
            .env("CISCO_SPLIT_INC_1_ADDR", "10.10.0.0")
            .env("CISCO_SPLIT_INC_1_MASKLEN", "16")
            .output()
            .expect("cscript.exe 是 Windows 自带组件，应当可用");
        assert!(output.status.success(), "cscript 执行失败");
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(
            stdout.contains("WS-WORKBENCH defdomain=example.com"),
            "默认域名没有回报给 worker：{}",
            stdout
        );
        // 服务端下发的是 198.51.100.0/22（上面的 MASKLEN=22），脚本按原样回报；
        // 归一化到网络地址是 worker 的活（见 `worker::tests::*server_scope*`），
        // 这里断言 /24 会是复制粘贴留下的旧期望值。
        assert!(
            stdout.contains("WS-WORKBENCH split=198.51.100.0/22"),
            "split-include 网段没有回报给 worker：{}",
            stdout
        );
        assert!(
            stdout.contains("WS-WORKBENCH split=10.10.0.0/16"),
            "第二条 split-include 网段没有回报给 worker：{}",
            stdout
        );
        // 回报同时要落到 script.log（openconnect 的 stdout 接不到 worker 的管道）。
        // 新脚本用 UTF-16LE 写，必须走 read_log 而不是 read_to_string。
        let log = read_log(&dir.join("script.log")).unwrap_or_default();
        assert!(
            log.contains("split=198.51.100.0/22"),
            "script.log 里也要有服务端下发的网段：{}",
            log
        );
        assert!(log.contains("DONE reason=connect"), "script.log 缺少结束标记：{}", log);
    }

