    #[test]
    fn windows_script_reports_connect() {
        let script = windows_script(&ctx());
        assert!(script.contains(r#"var MODE = "rule";"#));
        // 报告通道：reason 等关键参数仍要回报给 worker
        assert!(script.contains(r#"report("reason", "connect");"#));
        assert!(script.contains("WS-WORKBENCH "));
    }

    #[test]
    fn windows_script_sets_address_and_mtu() {
        let script = windows_script(&ctx());
        // 退化后脚本仍负责配接口地址与 MTU
        assert!(script.contains("netsh interface ip set address"));
        assert!(script.contains("mtu="));
    }

    #[test]
    fn windows_script_never_takes_default_route() {
        let script = windows_script(&ctx());
        // 规则分流：脚本不再接管默认路由，也不改 metric / 网关
        assert!(!script.contains("SET_GATEWAY"));
        assert!(!script.contains("metric=1 store=active"));
    }

    #[test]
    fn windows_script_never_touches_dns() {
        let script = windows_script(&ctx());
        // DNS 由 worker 按模式接管（规则模式走 NRPT，全局模式配隧道网卡），脚本一个 DNS 命令都不许发
        assert!(!script.contains("set dns"));
        assert!(!script.contains("USE_VPN_DNS"));
    }

    #[test]
    fn windows_script_never_writes_persistent_config() {
        let script = windows_script(&ctx());
        assert!(script.contains("store=active"));
        assert!(!script.contains("store=persistent"));
    }

    #[test]
    fn windows_script_escapes_session_path() {
        let script = windows_script(&ctx());
        // 反斜杠必须被转义，否则 JScript 会把 \U 之类当成转义序列
        assert!(script.contains(r#"C:\\Users\\demo"#));
    }

    #[test]
    fn windows_script_adds_host_route_to_avoid_loop() {
        let script = windows_script(&ctx());
        assert!(script.contains("route add \" + vpngw + \" mask 255.255.255.255 "));
        assert!(script.contains(r#"var ORIGINAL_GW = "192.168.1.1";"#));
    }

    #[test]
    fn macos_script_uses_route_and_ifconfig() {
        let script = macos_script(&ctx());
        assert!(script.contains(r#"MODE="rule""#));
        assert!(script.contains("report reason connect"));
        assert!(script.contains("WS-WORKBENCH "));
        assert!(script.contains("/sbin/route -n add -host"));
        assert!(script.contains("/sbin/ifconfig"));
        assert!(script.contains("mtu"));
        assert!(script.starts_with("#!/bin/sh"));
    }

    #[test]
    fn macos_script_reports_server_split_scope() {
        // 服务端下发的「公司内网范围」必须原样回报，否则 worker 只能靠用户手写规则，
        // 用户漏写一条域名就少覆盖一片内网。
        let script = macos_script(&ctx());
        assert!(script.contains(r#"report defdomain "${CISCO_DEF_DOMAIN:-}""#));
        assert!(script.contains(r#"report splitexc "${CISCO_SPLIT_EXC:-0}""#));
        assert!(script.contains("CISCO_SPLIT_INC"));
        assert!(script.contains(r#"report split "$split_addr/$split_mask""#));
    }

    #[test]
    fn windows_script_reports_server_split_scope() {
        // 和 macOS 脚本一致：服务端下发的默认域名 + split-include 网段必须回报，
        // 否则 Windows 侧只能靠用户手写规则，漏写一条就少覆盖一片内网。
        let script = windows_script(&ctx());
        assert!(script.contains(r#"report("defdomain", env("CISCO_DEF_DOMAIN") || "");"#));
        assert!(script.contains(r#"report("splitexc", env("CISCO_SPLIT_EXC") || "0");"#));
        assert!(script.contains("CISCO_SPLIT_INC_"));
        assert!(script.contains(r#"report("split", splitAddr + "/" + splitMask);"#));
    }

    #[test]
    fn macos_script_never_takes_default_route() {
        let script = macos_script(&ctx());
        // 规则分流：脚本不再接管默认路由
        assert!(!script.contains("add default"));
        assert!(!script.contains("0.0.0.0/1"));
        assert!(!script.contains("SET_GATEWAY"));
    }

    #[test]
    fn macos_script_never_touches_dns() {
        let script = macos_script(&ctx());
        // DNS 拦截由引擎负责，脚本不再碰系统 DNS
        assert!(!script.contains("setdnsservers"));
        assert!(!script.contains("USE_VPN_DNS"));
    }

    #[test]
    fn windows_script_is_pure_ascii() {
        // cscript.exe 在没有 BOM 时按系统 ANSI 代码页（中文 Windows 即 GBK）解码 .js，
        // 一个非 ASCII 字节就会让整个脚本编译失败。这条断言是那个坑的唯一防线。
        let script = windows_script(&ctx());
        assert!(
            script.is_ascii(),
            "windows_script 必须只包含 ASCII 字符，否则 cscript 无法解析"
        );
    }

    #[cfg(target_os = "windows")]
    #[test]
    fn windows_script_compiles_under_cscript() {
        // 直接复现踩过的坑：脚本里只要混进一个非 ASCII 字节，cscript 就按系统
        // ANSI 代码页解码失败并退出 1，而 openconnect 只会把它曲解成
        // "Failed to spawn script"。所以这里真的把脚本交给 cscript 编译一遍。
        let dir = std::env::temp_dir().join("ws-workbench-script-check");
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("vpnc-script-win.js");

        std::fs::write(&path, windows_script(&ctx())).unwrap();
        // reason 显式置空：脚本两个分支都不进，只会 WScript.Quit(0)，
        // 不会执行任何 netsh / route，动不到本机的网络配置。
        let output = std::process::Command::new("cscript.exe")
            .args(["//nologo", "//E:JScript"])
            .arg(&path)
            .env("reason", "")
            .output()
            .expect("cscript.exe 是 Windows 自带组件，应当可用");
        assert!(
            output.status.success(),
            "cscript 无法执行生成的脚本（{:?}）: {}{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );

        let _ = std::fs::remove_file(&path);
    }

    #[cfg(target_os = "windows")]
    #[test]
    fn windows_script_reports_split_scope_through_cscript() {
        // 真正用 cscript 跑一遍 connect 分支的「回报」部分：地址 / 网关 / MTU 全空，
        // 所以脚本不会执行任何 netsh / route，只会把服务端下发的范围写进 script.log
        // 和 stdout，动不到本机网络。
        let dir = std::env::temp_dir().join("ws-workbench-script-split");
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("vpnc-script-win.js");
        let ctx = ScriptContext {
            session_dir: &dir,
            original_gateway: "192.168.1.1",
        };
        std::fs::write(&path, windows_script(&ctx)).unwrap();
        let output = std::process::Command::new("cscript.exe")
            .args(["//nologo", "//E:JScript"])
            .arg(&path)
            .env("reason", "connect")
            .env("TUNDEV", "ws-tun")
            .env("TUNIDX", "77")
            .env("INTERNAL_IP4_ADDRESS", "")
            .env("INTERNAL_IP4_MTU", "")
            .env("INTERNAL_IP4_DNS", "192.0.2.12")
            .env("VPNGATEWAY", "")
            .env("CISCO_DEF_DOMAIN", "example.com")
            .env("CISCO_SPLIT_INC", "2")
            .env("CISCO_SPLIT_INC_0_ADDR", "198.51.100.0")
            .env("CISCO_SPLIT_INC_0_MASKLEN", "22")
            .env("CISCO_SPLIT_INC_1_ADDR", "10.10.0.0")
            .env("CISCO_SPLIT_INC_1_MASKLEN", "16")
            .output()
            .expect("cscript.exe 是 Windows 自带组件，应当可用");
        assert!(output.status.success(), "cscript 执行失败");
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(
            stdout.contains("WS-WORKBENCH defdomain=example.com"),
            "默认域名没有回报给 worker：{}",
            stdout
        );
        assert!(
            stdout.contains("WS-WORKBENCH split=198.51.100.0/24"),
            "split-include 网段没有回报给 worker：{}",
            stdout
        );
        assert!(
            stdout.contains("WS-WORKBENCH split=10.10.0.0/16"),
            "第二条 split-include 网段没有回报给 worker：{}",
            stdout
        );
        // 回报同时要落到 script.log（openconnect 的 stdout 接不到 worker 的管道）
        let log = std::fs::read_to_string(dir.join("script.log")).unwrap_or_default();
        assert!(log.contains("split=198.51.100.0/24"));
        let _ = std::fs::remove_file(&path);
        let _ = std::fs::remove_file(dir.join("script.log"));
    }

    #[test]
    fn parse_marker_line_reads_key_value() {
        let (key, value) = parse_marker_line("WS-WORKBENCH ip4=198.51.100.39").unwrap();
        assert_eq!(key, "ip4");
        assert_eq!(value, "198.51.100.39");
    }

