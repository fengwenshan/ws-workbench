//! Windows：**不使用本机 DNS 转发器，也不占用 53 端口**。
//!
//! 原设计是「NRPT 指向本机转发器 → 转发器按应答装 `/32` → 再回包」，好处是
//! `DOMAIN-SUFFIX` 的任意子域都能在应用拿到地址之前完成布线。实机证伪：
//!
//! - 转发器绑 `127.0.0.2:53`：`Get-NetUDPEndpoint` 能看到监听，NRPT 也写进去了，
//!   但探针查询 2.5 秒内一条都没进来；
//! - 转发器绑 `127.0.0.1:53`（同样空闲）：结果一样，零查询。
//!
//! 也就是说 Windows DNS Client 只把 NRPT 规则里的服务器当作「接口上的 DNS」来用，
//! 回环地址上没有接口，规则写完等于没用。既然这条路必然退回「NRPT 直连 VPN DNS +
//! 后台解析」，就没必要先去绑 53 —— 绑上去只会让 Clash / dnsmasq / AdGuard 在
//! 连接瞬间抢不到端口。
//!
//! 这个文件刻意不导出任何常量：地址策略在 Windows 上不存在。
